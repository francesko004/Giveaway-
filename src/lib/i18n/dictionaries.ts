export function isLocale(v: unknown): v is Locale {
  return v === "sq" || v === "en";
}

/** Resolves dotted keys like "errors.phone.invalid". Returns the key itself when missing. */
export function translate(dict: Dictionary, key: string, vars?: Record<string, string | number>): string {
  const value = key.split(".").reduce<unknown>((acc, k) => (acc && typeof acc === "object" ? (acc as Record<string, unknown>)[k] : undefined), dict);
  let s = typeof value === "string" ? value : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
