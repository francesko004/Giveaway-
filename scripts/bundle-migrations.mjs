// Embeds prisma/migrations/*/migration.sql into src/lib/migrations/bundle.ts so the app can apply
// migrations itself (needed on Cloudflare Workers, where the Prisma CLI cannot run).
//   node scripts/bundle-migrations.mjs          → write the bundle
//   node scripts/bundle-migrations.mjs --check  → exit 1 if the bundle is out of date
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const dir = "prisma/migrations";
const out = "src/lib/migrations/bundle.ts";
const migrations = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(path.join(dir, d.name, "migration.sql")))
  .map((d) => d.name)
  .sort()
  .map((name) => {
    const sql = readFileSync(path.join(dir, name, "migration.sql"), "utf8");
    return { name, checksum: createHash("sha256").update(sql).digest("hex"), sql };
  });

const body = `// AUTO-GENERATED by scripts/bundle-migrations.mjs — do not edit. Regenerate after adding a migration.
export interface BundledMigration { name: string; checksum: string; sql: string }

export const MIGRATIONS: BundledMigration[] = ${JSON.stringify(migrations, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== body) {
    console.error(`${out} is out of date — run: node scripts/bundle-migrations.mjs`);
    process.exit(1);
  }
  console.log("migration bundle up to date");
} else {
  writeFileSync(out, body);
  console.log(`bundled ${migrations.length} migrations into ${out}`);
}
